export function findCountryByCode(code: string): Country {
  const upper = code.toUpperCase();
  return COUNTRIES.find((c) => c.code === upper) ?? DEFAULT_COUNTRY;
}

export function findCountryByDialCode(dialCode: string): Country | undefined {
  const clean = dialCode.startsWith('+') ? dialCode : '+' + dialCode;
  return COUNTRIES.find((c) => c.dialCode === clean);
}

/**
 * Prefix-based search: matches countries starting from the first letter or dial code.
 */
export function searchCountries(query: string): Country[] {
  const q = query.trim().toLowerCase();
  if (!q) return COUNTRIES;

  const isDial = q.startsWith('+') || /^\d+$/.test(q);
  if (isDial) {
    const rawDigits = q.replace(/^\+/, '');
    return COUNTRIES.filter((c) => {
      const countryDigits = c.dialCode.replace(/^\+/, '');
      return countryDigits.startsWith(rawDigits) || c.dialCode.toLowerCase().startsWith(q);
    });
  }

  // Prefix matching for alphabetical query: starts with first letter/characters
  return COUNTRIES.filter(
    (c) =>
      c.name.toLowerCase().startsWith(q) ||
      c.code.toLowerCase().startsWith(q)
  );
}

export function formatPhoneNumber(raw: string, country: Country): string {
  let digits = raw.replace(/\D/g, '');
  const dialDigits = country.dialCode.replace(/\D/g, '');
  if (digits.startsWith(dialDigits) && digits.length > country.digitCount) {
    digits = digits.slice(dialDigits.length);
  }
  digits = digits.slice(0, country.digitCount);
  if (!country.format) return digits;

  let res = '';
  let dIdx = 0;
  for (let i = 0; i < country.format.length && dIdx < digits.length; i++) {
    if (country.format[i] === '#') {
      res += digits[dIdx++];
    } else {
      res += country.format[i];
    }
  }
  return res;
}

export function formatE164(dialCode: string, nationalNumber: string): string {
  const cleaned = nationalNumber.replace(/\D/g, '');
  const prefix = dialCode.startsWith('+') ? dialCode : '+' + dialCode;
  return prefix + cleaned;
}
